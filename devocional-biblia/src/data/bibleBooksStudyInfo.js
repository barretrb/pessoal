export function getBookStudyInfo(bookIdOrName) {
  if (!bookIdOrName) return null;
  const clean = bookIdOrName.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();
  return BIBLE_BOOKS_STUDY_INFO.find(b => {
    const bName = b.name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();
    const bId = b.id.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();
    return bName === clean || bId === clean || clean.startsWith(bName) || bName.startsWith(clean);
  }) || null;
}
