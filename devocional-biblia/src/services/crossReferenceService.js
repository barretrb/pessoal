export const crossReferenceService = {
  // Retorna as referências cruzadas de um versículo (mesclando nativas e canônicas)
  getReferences(bookName, chapter, verseNumber, nativeRefs = []) {
    const cleanBook = (bookName || 'Lucas').trim();
    const ch = String(chapter || '1').trim();
    const vNum = String(verseNumber || '1').trim();
    const key = `${cleanBook} ${ch}:${vNum}`;

    let canonical = CANONICAL_CROSS_REFERENCES[key] || [];
    // Fallback contextual por capítulo se o versículo específico não possuir entrada individual
    if (canonical.length === 0 && CANONICAL_CHAPTER_THEMES[`${cleanBook} ${ch}`]) {
      canonical = CANONICAL_CHAPTER_THEMES[`${cleanBook} ${ch}`];
    }
    const native = Array.isArray(nativeRefs) ? nativeRefs : [];

    // Mescla garantindo unicidade pela referência bíblica
    const seenRefs = new Set();
    const merged = [];

    // Prioriza referências canônicas com texto integral
    canonical.forEach(item => {
      const refName = item?.ref || item?.reference;
      if (refName && !seenRefs.has(refName)) {
        seenRefs.add(refName);
        merged.push({
          ...item,
          ref: refName,
          reference: refName
        });
      }
    });

    native.forEach(item => {
      const refName = item?.ref || item?.reference;
      if (refName && !seenRefs.has(refName)) {
        seenRefs.add(refName);
        merged.push({
          ...item,
          ref: refName,
          reference: refName
        });
      }
    });

    return merged;
  },

  // Verifica se o versículo possui referências cruzadas
  hasReferences(bookName, chapter, verseNumber, nativeRefs = []) {
    const refs = this.getReferences(bookName, chapter, verseNumber, nativeRefs);
    return refs.length > 0;
  }
};
